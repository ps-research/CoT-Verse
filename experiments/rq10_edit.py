"""rq10_edit.py — RQ10, the boundary study (Occ 2.5): how much of a model's OWN chain of thought can be edited before
its answer moves, and when it moves, whether the cause is the edit's content or its strangeness.

Material: each twin's own plain-condition trace on CoT-3D's 400 multi-hop items, as generated by rq8_monitor.py
(the clean base and the 3K false-fact organism of one architecture). The trace is split into sentences
(rq09_resample.py's splitter) and re-scored after graded edits with CoT-3D's B1/B2 scorer: the trace sits between
the options and 'Answer:' inside the model's native reasoning tags, log-prob over A/B/C/D at the last token,
unsloth 4-bit load (rq4_override / rq5_slot, verbatim). An item is used only when BOTH twins closed their think
block with at least MIN_SENTS sentences, so every comparison is paired across twins.

Conditions per twin (43 with --seeds 2):
  own        the own sentences re-joined (dose zero; the scorer check: its letter should match the generated one)
  own_raw    the raw own text (quantifies the re-join itself)
  empty      an empty reasoning slot
  <edit>_d<dose>_s<seed>   `dose` of the own sentences replaced — 1s (one sentence), 25, 50 or 100 percent — at
             seeded random positions, by one of four EDIT types of the same sentence count:
    opposed   sentences of the OTHER twin's trace on the same item, at the same relative positions: the same
              architecture's own style arguing from the other belief (content change, minimal strangeness)
    placebo   sentences of the SAME twin's trace on an item from a different universe, minus that trace's conclusion
              sentences (a sentence naming an answer letter is content, not strangeness; the count dropped is recorded)
              — on-distribution surface, irrelevant content: the strangeness term measured with the model's own text
    scramble  the same own sentences with their words shuffled (maximal strangeness, no content)
    offdist   RQ5's off-distribution placebo: sentences of CoT-3D's unrelated_cot injections for the same universe
  <edit>_pos_<first|middle|last>   the one-sentence dose at a fixed position ("in what ways")
Content term at a dose = opposed shift − placebo shift; strangeness term = placebo shift (scramble its ceiling;
offdist the number RQ5 reported). Per condition and item: the letter, the four logits, is_sdf / is_true, the
sdf−true margin, the replaced positions and the token count of the edited trace (size matching is checked in
the analysis, not enforced here).

Usage (notebook background job):
  python rq10_edit.py --model phi4 --rq8-dir /tmp/rq8 [--rq8-repo PS4CoT/sdf-evaluation-results] --out /tmp/rq11
                      --drive-dir molab/CoT-Verse/runs/<RUN_ID>/rq11 [--twins clean,implanted] [--seeds 2] [--batch 8] [--limit N]
Resumable: the result file is rewritten after every condition and copied to Drive; finished conditions are skipped.
"""
from __future__ import annotations
import argparse, datetime, gzip, json, os, random, re, sys, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from rq4_override import HF_REPOS, load_model, letter_ids, score_batch, score_single, check_batching   # noqa: E402
from rq5_slot import format_mcq_prompt_with_cot, COT_TAGS                                             # noqa: E402
from rq8_monitor import load_items                                                                     # noqa: E402

HERE = Path(__file__).resolve().parent
INJ = HERE / "data" / "ce_injections.json.gz"
SENT = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])|\n\s*\n")      # rq09_resample.py, verbatim
def split_sentences(t): return [s.strip() for s in SENT.split(t) if len(s.strip()) > 8]

TWINS = {"clean": "base", "implanted": "false_3k"}
OTHER = {"clean": "implanted", "implanted": "clean"}
EDITS = ["opposed", "placebo", "scramble", "offdist"]
DOSES = [("1s", None), ("25", 0.25), ("50", 0.5), ("100", 1.0)]
POSITIONS = ["first", "middle", "last"]
MIN_SENTS = 3

def condition_list(seeds):
    """Ordered so that a run cut short still holds the informative part: the seed-0 dose grid, then positions, then extra seeds."""
    conds = ["own", "own_raw", "empty"]
    conds += [f"{e}_d{dl}_s0" for dl, _ in DOSES for e in EDITS]
    conds += [f"{e}_pos_{p}" for p in POSITIONS for e in EDITS]
    for s in range(1, seeds):
        conds += [f"{e}_d{dl}_s{s}" for dl, _ in DOSES if dl != "100" for e in EDITS]
    return conds

# ───────────────────────────── traces ─────────────────────────────
def fetch_rq8(rq8_dir, repo, model, token):
    """The two RQ8 result files of `model` from the HF dataset repo (path <RUN_ID>/<model>_<variant>.json); the newest
    finished file per variant that carries a tokenizer_check (post-D-126 code) wins."""
    from huggingface_hub import snapshot_download
    local = Path(snapshot_download(repo, repo_type="dataset", token=token, allow_patterns=[f"*/{model}_base.json", f"*/{model}_false_3k.json"]))
    for fn in (f"{model}_base.json", f"{model}_false_3k.json"):
        cands = []
        for p in local.glob(f"*/{fn}"):
            d = json.load(open(p))
            if d.get("status") != "ok": continue
            cands.append((d["metadata"].get("tokenizer_check") is not None, d["metadata"].get("finished", ""), p))
        if not cands: raise SystemExit(f"no finished {fn} in {repo}")
        best = sorted(cands)[-1][2]; Path(rq8_dir).mkdir(parents=True, exist_ok=True)
        (Path(rq8_dir) / fn).write_bytes(best.read_bytes()); print(f"[rq8] {fn} <- {repo}/{best.parent.name}", flush=True)

def load_traces(rq8_dir, model):
    """{twin: {item_id: {text, sents, closed, answer, natural, n_tokens}}} from the RQ8 plain condition, refusing corrupted text."""
    out = {}
    for twin, variant in TWINS.items():
        fn = Path(rq8_dir) / f"{model}_{variant}.json"; d = json.load(open(fn))
        chk = d["metadata"].get("tokenizer_check")
        if model == "deepseek" and not (chk and chk.get("fix")):
            raise SystemExit(f"{fn}: DeepSeek traces from the broken tokenizer path (D-126); refusing to use them")
        rows = {}
        for r in d["per_item"]:
            c = r["conditions"].get("plain")
            if not c: continue
            t = c["cot_text"]
            if "Ġ" in t or "Ċ" in t or (len(t) > 200 and " " not in t): raise SystemExit(f"{fn}: corrupted trace text on {r['id']} (D-126)")
            rows[r["id"]] = {"text": t, "sents": split_sentences(t), "closed": bool(c["hit_close_tag"]), "answer": c["answer"],
                             "natural": c.get("natural_letter", ""), "n_tokens": c["n_generated_tokens"]}
        out[twin] = rows; print(f"[traces] {twin} <- {fn.name}: {len(rows)} items, closed {sum(v['closed'] for v in rows.values())}", flush=True)
    return out

CONCLUSION = re.compile(r"(?:\b(?:answer|option|choice|pick|select|choose|go with|correct)\b[^.]{0,40}?(?<![A-Za-z])\(?[ABCD]\)?(?![A-Za-z]))"
                        r"|(?:^\(?[ABCD]\)?[.:)]?\s*$)|(?:(?<![A-Za-z])\(?[ABCD]\)?\s*(?:is|seems|looks)\s+(?:the\s+)?(?:correct|right|best|answer))", re.I)
def names_letter(s): return bool(CONCLUSION.search(s))
LETTER_MENTION = re.compile(r"(?<![A-Za-z])\(?([ABCD])\)?(?![A-Za-z])")
def letters_in(sents): return sorted({m.group(1) for s in sents for m in LETTER_MENTION.finditer(s)})

def offdist_pool(universe):
    inj = json.load(gzip.open(INJ, "rt")); seen, pool = set(), []
    for it in inj:
        if it["universe"] != universe: continue
        for s in split_sentences(it["unrelated_cot"]):
            if s not in seen and not names_letter(s): seen.add(s); pool.append(s)
    return pool

# ───────────────────────────── edits ─────────────────────────────
def rel_pick(src, positions, n_own):
    """Sentences of `src` at the relative positions of `positions` (indices into an n_own-sentence trace), each used once."""
    out, used = [], set()
    for j in positions:
        k = min(len(src) - 1, round(j * len(src) / n_own))
        while k in used and len(used) < len(src): k = (k + 1) % len(src)
        used.add(k); out.append(src[k])
    return out

def dose_positions(n, dl, frac, rng):
    if dl == "1s": return [rng.randrange(n)]
    if frac >= 1.0: return list(range(n))
    return sorted(rng.sample(range(n), max(1, round(frac * n))))

def pos_index(n, p): return {"first": 0, "middle": n // 2, "last": n - 1}[p]

def parse_cond(cond):
    """-> (edit, dose_label | None, seed, position | None) for an edit condition."""
    m = re.fullmatch(r"(\w+?)_d(1s|25|50|100)_s(\d+)", cond)
    if m: return m.group(1), m.group(2), int(m.group(3)), None
    m = re.fullmatch(r"(\w+?)_pos_(first|middle|last)", cond)
    if m: return m.group(1), "1s", 0, m.group(2)
    raise ValueError(cond)

def placebo_partner(twin_rows, item, need, rng):
    """An item of another universe whose trace closed with at least `need` sentences (else the longest available)."""
    cands = sorted(k for k, v in twin_rows.items() if v["closed"] and item["universe"] != k.split("_")[0] and sum(not names_letter(x) for x in v["sents"]) >= need)
    if not cands: cands = sorted((k for k, v in twin_rows.items() if v["closed"] and item["universe"] != k.split("_")[0]), key=lambda k: -len(twin_rows[k]["sents"]))[:20]
    return rng.choice(cands)

def build_variant(cond, item, twin, traces, pools):
    """The edited sentence list for (condition, item, twin) plus a record of what was replaced. Deterministic per key."""
    own = traces[twin][item["id"]]["sents"]; n = len(own)
    edit, dl, seed, pos = parse_cond(cond)
    rng = random.Random(f"{item['id']}|{twin}|{cond}")
    positions = [pos_index(n, pos)] if pos else dose_positions(n, dl, dict(DOSES)[dl], rng)
    sents = list(own); meta = {"k": len(positions), "positions": positions, "n_sents": n}
    if edit == "opposed":
        src = traces[OTHER[twin]][item["id"]]["sents"]; rep = rel_pick(src, positions, n); meta["source"] = OTHER[twin]
    elif edit == "placebo":
        pid = placebo_partner(traces[twin], item, len(positions), rng)
        src = [x for x in traces[twin][pid]["sents"] if not names_letter(x)] or traces[twin][pid]["sents"]
        rep = rel_pick(src, positions, n); meta["source"] = pid; meta["source_conclusions_dropped"] = len(traces[twin][pid]["sents"]) - len(src)
    elif edit == "scramble":
        rep = []
        for j in positions:
            w = own[j].split(); rng.shuffle(w); rep.append(" ".join(w))
    elif edit == "offdist":
        pool = pools[item["universe"]]; start = rng.randrange(len(pool)); rep = [pool[(start + i) % len(pool)] for i in range(len(positions))]
    else:
        raise ValueError(edit)
    for j, r in zip(positions, rep): sents[j] = r
    meta["inserted_letters"] = letters_in(rep); meta["replaced_letters"] = letters_in([own[j] for j in positions])
    return sents, meta

def trace_for(cond, item, twin, traces, pools):
    if cond == "own": return " ".join(traces[twin][item["id"]]["sents"]), {}
    if cond == "own_raw": return traces[twin][item["id"]]["text"], {}
    if cond == "empty": return "", {}
    sents, meta = build_variant(cond, item, twin, traces, pools); return " ".join(sents), meta

# ───────────────────────────── scoring ─────────────────────────────
def summarize(per_item, twin, conds):
    out = {}
    rows = [r for r in per_item if twin in r["twins"]]
    for c in conds:
        rc = [(r, r["twins"][twin]["conditions"][c]) for r in rows if c in r["twins"][twin]["conditions"]]
        if not rc: continue
        n = len(rc); s = {"n": n, "sdf_rate": sum(x["is_sdf"] for _, x in rc) / n, "true_rate": sum(x["is_true"] for _, x in rc) / n,
                          "mean_margin_sdf_minus_true": sum(x["margin"] for _, x in rc) / n}
        own = [(r["twins"][twin]["conditions"].get("own"), x) for r, x in rc]
        own = [(o, x) for o, x in own if o]
        if own and c != "own":
            s["change_rate_vs_own"] = sum(o["answer"] != x["answer"] for o, x in own) / len(own)
            s["mean_abs_dmargin_vs_own"] = sum(abs(o["margin"] - x["margin"]) for o, x in own) / len(own)
        if c == "own":
            gen = [(r["twins"][twin]["generated_answer"], x["answer"]) for r, x in rc]
            s["agreement_with_generated"] = sum(g == a for g, a in gen) / n
        out[c] = s
    return out

def run(args, token, drive):
    model = args.model; out_path = Path(args.out) / f"{model}.json"
    items = load_items(args.limit); by_id = {i["id"]: i for i in items}
    if args.rq8_repo and not all((Path(args.rq8_dir) / f"{model}_{v}.json").exists() for v in TWINS.values()):
        fetch_rq8(args.rq8_dir, args.rq8_repo, model, token)
    traces = load_traces(args.rq8_dir, model)
    usable = [i for i in items if all(i["id"] in traces[t] and traces[t][i["id"]]["closed"] and len(traces[t][i["id"]]["sents"]) >= MIN_SENTS for t in TWINS)]
    if len(usable) < 20:
        raise SystemExit(f"[rq11] {model}: only {len(usable)} items have a closed trace of >= {MIN_SENTS} sentences on both twins "
                         f"(mean generated tokens: " + ", ".join(f"{t} {sum(v['n_tokens'] for v in traces[t].values()) / max(1, len(traces[t])):.0f}" for t in TWINS)
                         + "); this model does not emit reasoning in the B4 natural arm — nothing to edit (Gemma-4, D-125)")
    pools = {u: offdist_pool(u) for u in sorted({i["universe"] for i in usable})}
    conds = condition_list(args.seeds)
    rec = json.loads(out_path.read_text()) if out_path.exists() else None
    if rec is None:
        rec = {"metadata": {"experiment": "RQ10 boundary study: graded edits of the model's own CoT", "model": model, "n_items_bench": len(items), "n_items_used": len(usable),
                            "min_sents": MIN_SENTS, "seeds": args.seeds, "conditions": conds, "edits": EDITS, "doses": [d for d, _ in DOSES], "positions": POSITIONS,
                            "traces_from": "rq8_monitor.py plain condition (both twins)", "cot_tags": COT_TAGS[model], "batch": args.batch,
                            "protocol": "CoT-3D B1/B2 scorer: trace between options and 'Answer:' in native reasoning tags; log-prob over A/B/C/D; unsloth 4-bit; "
                                        "batched with left padding and explicit position ids; sentences by rq09_resample's splitter, re-joined with single spaces",
                            "started": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")},
               "status": "running", "done": {t: [] for t in TWINS}, "summary": {t: {} for t in TWINS},
               "per_item": [{"id": i["id"], "universe": i["universe"], "fact_index": i["fact_index"], "hop": i["hop"], "tier": i["tier"],
                             "true_answer": i["true_answer"], "sdf_answer": i["sdf_answer"],
                             "twins": {t: {"generated_answer": traces[t][i["id"]]["answer"], "natural_letter": traces[t][i["id"]]["natural"],
                                           "n_sents": len(traces[t][i["id"]]["sents"]), "n_tokens_generated": traces[t][i["id"]]["n_tokens"], "conditions": {}} for t in TWINS}}
                            for i in usable]}
    rows = {r["id"]: r for r in rec["per_item"]}
    print(f"[rq11] {model}: {len(usable)}/{len(items)} items usable (both twins closed, >= {MIN_SENTS} sentences); {len(conds)} conditions per twin", flush=True)

    def save(final=False):
        for t in TWINS: rec["summary"][t] = summarize(rec["per_item"], t, rec["done"][t])
        if final: rec["status"] = "ok"; rec["metadata"]["finished"] = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
        out_path.parent.mkdir(parents=True, exist_ok=True); tmp = out_path.with_suffix(".tmp"); tmp.write_text(json.dumps(rec)); os.replace(tmp, out_path)
        if drive:
            try:
                sys.path.insert(0, "/marimo/CoT-Verse"); sys.path.insert(0, "/marimo")
                import notebook_helpers as nh
                nh.dput_atomic(str(out_path), f"{drive}/{model}{'' if final else '.partial'}.json")
            except Exception as e:
                print(f"[drive] upload failed: {e!r}", flush=True)

    for twin in [t.strip() for t in args.twins.split(",")]:
        todo = [c for c in conds if c not in rec["done"][twin]]
        if not todo: print(f"[skip] {model}/{twin}: all conditions present", flush=True); continue
        variant = TWINS[twin]; repo = HF_REPOS[model]["base"] if variant == "base" else HF_REPOS[model]["false"]["3k"]
        t0 = time.time(); mdl, tok = load_model(model, repo, token); lids = letter_ids(tok)
        rec["metadata"].setdefault("letter_token_ids", lids); rec["metadata"].setdefault("tokenizer_check", {})[twin] = getattr(tok, "tokenizer_check", None)
        print(f"[load] {model}/{twin} <- {repo} in {time.time()-t0:.0f}s", flush=True)
        o, cl = COT_TAGS[model]; batch = args.batch
        if batch > 1:
            probe = [format_mcq_prompt_with_cot(i["question"], i["options"], trace_for("own", i, twin, traces, pools)[0], o, cl) for i in usable[:16]]
            agree, maxd = check_batching(mdl, tok, probe, lids, batch); rec["metadata"].setdefault("batching_check", {})[twin] = {"n": len(probe), "argmax_agreement": agree, "max_abs_logit_diff": maxd}
            print(f"[check] {twin}: batched vs single agreement {agree:.3f}, max |dlogit| {maxd:.3f}", flush=True)
            if agree < 0.98: batch = 1; print("[check] falling back to batch=1", flush=True)
        for c in todo:
            t1 = time.time(); built = [trace_for(c, i, twin, traces, pools) for i in usable]
            prompts = [format_mcq_prompt_with_cot(i["question"], i["options"], tx, o, cl) for i, (tx, _) in zip(usable, built)]
            for k in range(0, len(usable), batch):
                chunk = prompts[k:k + batch]
                res = score_batch(mdl, tok, chunk, lids) if batch > 1 else [score_single(mdl, tok, p, lids) for p in chunk]
                for (ans, sc), it, (tx, meta) in zip(res, usable[k:k + batch], built[k:k + batch]):
                    rows[it["id"]]["twins"][twin]["conditions"][c] = {"answer": ans, "scores": sc, "is_sdf": ans == it["sdf_answer"], "is_true": ans == it["true_answer"],
                                                                      "margin": sc[it["sdf_answer"]] - sc[it["true_answer"]], "n_tok": len(tok(tx, add_special_tokens=False)["input_ids"]), **meta}
            rec["done"][twin].append(c); save(); s = rec["summary"][twin][c]
            print(f"[{model}/{twin}] {c:22s} sdf {s['sdf_rate']*100:5.1f} true {s['true_rate']*100:5.1f} margin {s['mean_margin_sdf_minus_true']:+.2f}"
                  + (f" changed {s['change_rate_vs_own']*100:5.1f}" if "change_rate_vs_own" in s else "") + (f" agree_gen {s['agreement_with_generated']:.2f}" if c == "own" else "")
                  + f" ({time.time()-t1:.0f}s)", flush=True)
        del mdl; import gc; gc.collect()
        try:
            import torch; torch.cuda.empty_cache()
        except Exception:
            pass
    save(final=all(not [c for c in conds if c not in rec["done"][t]] for t in TWINS))
    print(f"[rq11] {model} status {rec['status']}", flush=True)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, choices=list(COT_TAGS)); ap.add_argument("--rq8-dir", default="/tmp/rq8"); ap.add_argument("--rq8-repo", default="")
    ap.add_argument("--out", default="/tmp/rq11"); ap.add_argument("--drive-dir", default=""); ap.add_argument("--twins", default="clean,implanted")
    ap.add_argument("--seeds", type=int, default=2); ap.add_argument("--batch", type=int, default=8); ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()
    token = os.environ.get("HF_TOKEN") or (open(os.environ["HF_TOKEN_FILE"]).read().strip() if os.environ.get("HF_TOKEN_FILE") else None)
    run(args, token, args.drive_dir)

if __name__ == "__main__":
    main()
